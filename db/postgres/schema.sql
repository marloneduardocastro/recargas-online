-- Modelo relacional de la solución (PostgreSQL)
-- psql -d recargas -f db/postgres/schema.sql

CREATE TABLE operador (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL,
    activo  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_operador_nombre UNIQUE (nombre)
);

CREATE TABLE vendedor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_documento VARCHAR(20)  NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_vendedor_documento UNIQUE (numero_documento)
);

CREATE TABLE recarga (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operador_id    BIGINT        NOT NULL,
    vendedor_id    BIGINT        NOT NULL,
    numero_celular VARCHAR(10)   NOT NULL,
    valor          NUMERIC(12,2) NOT NULL,
    fecha_venta    TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recarga_operador FOREIGN KEY (operador_id) REFERENCES operador (id),
    CONSTRAINT fk_recarga_vendedor FOREIGN KEY (vendedor_id) REFERENCES vendedor (id),
    CONSTRAINT ck_recarga_celular  CHECK (numero_celular ~ '^3[0-9]{9}$'),
    CONSTRAINT ck_recarga_valor    CHECK (valor BETWEEN 1000 AND 500000)
);

CREATE INDEX ix_recarga_operador ON recarga (operador_id);
CREATE INDEX ix_recarga_vendedor ON recarga (vendedor_id);
CREATE INDEX ix_recarga_fecha    ON recarga (fecha_venta);

